"""Measure reels you have saved locally (observations only, no interpretation).

    python research/analyze_reels.py private/research/<channel> --log research/<channel>_log.csv --out research/<channel>_measured.md

For each .mp4: duration, resolution, shot cuts (ffmpeg scene score > 0.3), cuts per 10 s, time of the
first cut, speech-band vs overall loudness, and a first-3-seconds contact sheet PNG.
Merges optional metadata/notes from --log (columns from research/templates/reel_log_template.csv).
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import subprocess
from pathlib import Path


def probe(p):
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration:stream=width,height",
                        "-of", "json", str(p)], capture_output=True, text=True)
    d = json.loads(r.stdout)
    st = next((s for s in d.get("streams", []) if "width" in s), {})
    return float(d["format"]["duration"]), st.get("width"), st.get("height")


def cuts(p):
    r = subprocess.run(["ffmpeg", "-hide_banner", "-i", str(p), "-vf", "select='gt(scene,0.3)',showinfo", "-f", "null", "-"],
                       capture_output=True, text=True)
    return [float(x) for x in re.findall(r"pts_time:([\d.]+)", r.stderr)]


def loud(p, filt=""):
    af = (filt + "," if filt else "") + "ebur128"
    r = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-i", str(p), "-af", af, "-f", "null", "-"],
                       capture_output=True, text=True)
    m = re.findall(r"I:\s+(-?[\d.]+) LUFS", r.stderr)
    return float(m[-1]) if m else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("folder")
    ap.add_argument("--log")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    notes = {}
    if a.log and Path(a.log).exists():
        notes = {r["file"]: r for r in csv.DictReader(open(a.log, encoding="utf-8"))}
    rows = []
    sheets = Path(a.out).with_suffix("")
    sheets.mkdir(parents=True, exist_ok=True)
    for f in sorted(Path(a.folder).glob("*.mp4")):
        dur, w, h = probe(f)
        c = cuts(f)
        subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", str(f), "-t", "3", "-vf", "fps=2,scale=180:-1,tile=6x1",
                        "-frames:v", "1", str(sheets / f"{f.stem}_first3s.png")])
        rows.append(dict(file=f.name, duration=round(dur, 1), res=f"{w}x{h}", cuts=len(c),
                         cuts_per_10s=round(len(c) / dur * 10, 2) if dur else 0, first_cut=round(c[0], 2) if c else None,
                         lufs=loud(f), speech_band_lufs=loud(f, "highpass=f=300,lowpass=f=3400"), **notes.get(f.name, {})))
    keys = list(dict.fromkeys(k for r in rows for k in r))
    md = ["# Measured reel observations", "", "Generated by research/analyze_reels.py – measurements are observations; "
          "any 'why' must be labelled as hypothesis.", "", "| " + " | ".join(keys) + " |", "|" + "---|" * len(keys)]
    md += ["| " + " | ".join(str(r.get(k, "")) for k in keys) + " |" for r in rows]
    Path(a.out).write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{len(rows)} reels measured -> {a.out}")


if __name__ == "__main__":
    main()
